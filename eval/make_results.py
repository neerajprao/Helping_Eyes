"""
Writes markdown/eval_results.md from the result files in eval/results/ (and eval/data/user_study.csv). Never edit
the generated file by hand: change the evaluation, run it again, and run this.

    .venv/bin/python eval/make_results.py

A part whose results do not exist yet is shown as "not run yet".
"""

import csv
import os
import re
import statistics
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as C  # noqa: E402

OUT = os.path.join(C.ROOT, "markdown", "eval_results.md")
NAMES = {"gemini": "Gemini Flash-Lite", "qwen3b": "Qwen 2.5 3B"}
PAGE_PAUSE = 0.1           # app.js liveLoop: setTimeout(liveLoop, 100) after each reply
ENGINE = {"apple_vision": "Apple Vision", "app_capture": "App capture (Apple Vision + fixes)", "rapidocr": "RapidOCR",
          "tesseract": "Tesseract"}


def res(name):
    return C.load_json(os.path.join(C.RESULTS, name))


def pct(x, digits=1):
    return "–" if x is None else f"{x * 100:.{digits}f} %"


def ci(c):
    return f" ({pct(c[0])}–{pct(c[1])})" if c else ""


def sec(x):
    return "–" if x is None else f"{x:.2f} s"


def met(ok):
    return "–" if ok is None else ("✅ met" if ok else "❌ not met")


def user_study():
    path = os.path.join(C.EVAL, "data", "user_study.csv")
    if not os.path.exists(path):
        return None
    with open(path, newline="", encoding="utf-8") as f:
        rows = [r for r in csv.DictReader(f) if r.get("participant")]
    return rows or None


def main():
    photo, qa, exp, web, lat, book = (res("photo_eval_summary.json"), res("qa_summary.json"), res("expiry.json"),
                                      res("web_safety.json"), res("latency.json"), res("book.json"))
    exp = exp if exp and "summary" in exp else None          # a run still in progress has no summary yet
    users = user_study()
    L = ["# Helping Eyes: evaluation results", "",
         "Generated by `eval/make_results.py` from `eval/results/*.json`; do not edit by hand. How every number is "
         "measured: `markdown/eval_plan.md` and the docstring of each script in `eval/`. Bad results are reported as "
         "they are. Answers are checked against a fixed evaluation date, "
         f"{C.EVAL_DATE.strftime('%d %B %Y')}.", ""]

    # ---------------------------------------------------------------- headline table
    L += ["## Against the targets of the requirements document", "",
          "| Metric (requirement) | Target | Result | |", "|---|---|---|---|"]
    if photo:
        cap = photo["engines"]["app_capture"]
        cer = 1 - cap["key_line_accuracy"]
        L.append(f"| OCR character error rate on key lines (FR-2), app capture, {photo['photos']} photos | ≤ 0.05 | "
                 f"{cer:.3f} (accuracy {pct(cap['key_line_accuracy'])}) | {met(cer <= 0.05)} |")
    if qa:
        for m in ("gemini", "qwen3b"):
            d = qa["by_model"][m]
            a = d["accuracy"]
            L.append(f"| Answer accuracy, factual questions (FR-4), {NAMES[m]} | ≥ 90 % | {pct(a['accuracy'])}{ci(a['ci95'])}, "
                     f"n = {a['scored']} | {met(a['accuracy'] is not None and a['accuracy'] >= 0.9)} |")
        for m in ("gemini", "qwen3b"):
            r = qa["by_model"][m]["not_in_text_recall"]
            L.append(f"| \"Not in the text\" recall (FR-6, NFR-5), {NAMES[m]} | ≥ 90 % | {pct(r['rate'])}{ci(r['ci95'])}, "
                     f"n = {r['of']} | {met(r['rate'] is not None and r['rate'] >= 0.9)} |")
        for m in ("gemini", "qwen3b"):
            u = qa["by_model"][m]["numbers_not_in_text"]
            j = (qa.get("judge") or {}).get(m)
            extra = f"; free-text answers judged unsupported: {pct(j['unsupported_rate'])}, n = {j['n']}" if j else ""
            worst = max(u["rate"] or 0, (j or {}).get("unsupported_rate") or 0)
            L.append(f"| Unsupported claims (NFR-5), {NAMES[m]} | ≤ 5 % | answers with a number not in the text: "
                     f"{pct(u['rate'])}, n = {u['of']}{extra} | {met(worst <= 0.05)} |")
    if exp:
        s = exp["summary"]
        L.append(f"| Expiry verdict computed in code (FR-7, NFR-6), {s['cases']} label texts | 100 % | "
                 f"{s['code']['correct']}/{s['code']['scored']} | {met(s['code']['correct'] == s['code']['scored'])} |")
        for m in ("gemini", "qwen3b"):
            d = s[f"app_{m}"]
            L.append(f"| Spoken expiry verdict, {NAMES[m]} | 100 % | {d['correct']}/{d['scored']} | "
                     f"{met(d['scored'] and d['correct'] == d['scored'])} |")
    if web:
        nfr = [q for q in web["item_only_not_blocked"] if re.search(r"expir|best before|use by|batch|lot|price|mrp|cost", q, re.I)]
        offers = sum(qa["by_model"][m]["web_offers_on_item_only"] for m in qa["by_model"]) if qa else None
        L.append(f"| Web answers labelled \"According to the web\" (NFR-6) | 100 % | {web['labelled']}/{web['answered']} | "
                 f"{met(web['answered'] and web['labelled'] == web['answered'])} |")
        L.append(f"| Web lookups offered for expiry, batch or price (NFR-6) | 0 | {len(nfr)} wordings not blocked"
                 + (f"; offers in the Gemini vs Qwen run: {offers}" if qa else "")
                 + (f" (outside NFR-6, not blocked: {', '.join(q for q in web['item_only_not_blocked'] if q not in nfr)})" if len(web["item_only_not_blocked"]) > len(nfr) else "")
                 + f" | {met(not nfr and not offers)} |")
        L.append(f"| Health web answers end with the pharmacist reminder (NFR-6) | 100 % | {web['health_with_reminder']}/{web['health']} | "
                 f"{met(web['health'] and web['health_with_reminder'] == web['health'])} |")
    if lat:
        o = lat["ops"]
        for m in ("gemini", "qwen3b"):
            d, t = o.get(f"first_word_{m}"), o.get(f"ask_first_{m}")
            if d:
                within = f"; {sum(x <= 2.0 for x in d['values'])}/{d['n']} within 2 s, range {sec(d['min'])}–{sec(d['max'])}" if d.get("values") else ""
                L.append(f"| Question to the start of the spoken answer, p90 (NFR-1), {NAMES[m]} | ≤ 2.0 s | {sec(d['p90'])} "
                         f"(p50 {sec(d['p50'])}; text of the first sentence alone: p90 {sec(t['p90'])}{within}), n = {d['n']} | {met(d['p90'] <= 2.0)} |")
        L.append(f"| Capture, p90 (NFR-1) | ≤ 0.5 s | {sec(o['capture']['p90'])} (p50 {sec(o['capture']['p50'])}) | {met(o['capture']['p90'] <= 0.5)} |")
        page_rate = round(1 / (PAGE_PAUSE + o["live_label"]["p50"]), 1)
        L.append(f"| Live detection rate (NFR-1) | ≥ 10 checks/s | {page_rate} checks/s as the page sends frames (it waits "
                 f"{PAGE_PAUSE * 1000:.0f} ms after each reply); the server alone could take {o['live_checks_per_second']} a second | "
                 f"{met(page_rate >= 10)} |")
    if book and book.get("pages"):
        p = book["pages"]
        L.append(f"| Page numbers on real book photos (FR-10) | ≥ 90 % | {p['page_numbers']['yes']}/{p['page_numbers']['of']} | "
                 f"{met(p['page_numbers']['rate'] is not None and p['page_numbers']['rate'] >= 0.9)} |")
        # what book mode reads: the model's paragraphs where it grouped them in time, the layout order elsewhere
        read = [r["arranged"] or r["layout"] for r in p["rows"]]
        pairs = sum(x["pairs"] for x in read)
        rate = sum(x["pairs_in_order"] for x in read) / pairs if pairs else None
        L.append(f"| Reading order on real book photos (FR-9), pairs of key lines in order | ≥ 90 % | {pct(rate)} as book mode reads "
                 f"(layout {pct(p['order_layout']['rate'])}, with the model's paragraphs {pct(p['order_arranged_qwen3b']['rate'])}) | "
                 f"{met(rate is not None and rate >= 0.9)} |")
    if book and book.get("video"):
        v = book["video"]
        ok = v["pages_expected"] - v["missed"]
        L.append(f"| Page-turn detection on a real video (FR-9) | ≥ 95 % | {ok}/{v['pages_expected']} pages read, {v['extra']} extra | "
                 f"{met(ok / v['pages_expected'] >= 0.95 and v['extra'] == 0)} |")
    if users:
        overall = [float(r["q_overall"]) for r in users if r["q_overall"]]
        t1 = [r for r in users if r["t1_success"] == "1" and r["t1_seconds"] and float(r["t1_seconds"]) <= 120]
        L.append(f"| User rating (overall, 1–5) | ≥ 4.0, 5+ users | {statistics.mean(overall):.2f}, n = {len(overall)} | "
                 f"{met(len(overall) >= 5 and statistics.mean(overall) >= 4.0)} |")
        L.append(f"| Expiry date heard in under 2 min, first use, eyes closed (NFR-8) | – | {len(t1)}/{len(users)} | – |")
    missing = [n for n, d in (("photo test", photo), ("Gemini vs Qwen", qa), ("expiry test", exp), ("web safety", web),
                              ("speed", lat), ("book photos", book and book.get("pages")), ("page-turn video", book and book.get("video")),
                              ("user study", users)) if not d]
    if missing:
        L += ["", f"Not run yet: {', '.join(missing)}."]

    # ---------------------------------------------------------------- OCR
    if photo:
        L += ["", "## 1. Reading the text (OCR)", "",
              f"{photo['photos']} phone photos ({', '.join(f'{v} {k.replace(chr(95), chr(32))}' for k, v in photo.get('categories', {}).items())}). "
              "Reference: Claude's own reading of every photo (key printed lines and fields), written before any engine's text "
              "was seen. Full tables: `markdown/eval_photo_summary.md`.", "",
              "| Engine | Key-line accuracy | Character error rate | Fields found | Mean time |", "|---|---|---|---|---|"]
        for k, e in photo["engines"].items():
            L.append(f"| {ENGINE[k]} | {pct(e['key_line_accuracy'])}{ci(e['key_line_accuracy_ci95'])} | {1 - e['key_line_accuracy']:.3f} | "
                     f"{pct(e['fields_found_rate'])} | {sec(e['seconds_mean'])} |")
        L += ["", "| Group | Photos | Apple Vision | App capture | RapidOCR | Tesseract |", "|---|---|---|---|---|---|"]
        for g, d in photo["by_category"].items():
            L.append(f"| {g} | {d['photos']} | " + " | ".join(pct(d[k]) for k in ENGINE) + " |")
        L += ["", "*App capture* = what the app keeps (the best of the original, flattened, tone-corrected and binarised "
              "versions; for book pages the book path). The difference between it and plain Apple Vision is what the "
              "app's own image fixes add."]

    # ---------------------------------------------------------------- QA
    if qa:
        L += ["", "## 2. Answers: Gemini vs Qwen", "",
              f"{qa['photos']} photos ({', '.join(f'{v} {k.replace(chr(95), chr(32))}' for k, v in qa['categories'].items())}), "
              f"{qa['questions']} questions, each asked to both models through the app's own path, temperature "
              f"{qa['temperature']}. Models: {qa['models']['gemini']} and {qa['models']['qwen3b']}. Each model got the text the "
              "app kept after the capture, so reading mistakes reach the answers too.", "",
              "| | " + " | ".join(NAMES[m] for m in ("gemini", "qwen3b")) + " |", "|---|---|---|"]
        rows = [("Factual answers correct", "accuracy"),
                ("… when the value was in the text it got (the model's own accuracy)", "accuracy_value_in_text"),
                ("… when the reading missed or garbled the value (right only if the model repairs the reading)", "accuracy_value_not_in_text"),
                ("… pharmacy photos", "accuracy_pharmacy"), ("… other categories", "accuracy_other")]
        g, q = qa["by_model"]["gemini"]["answered"], qa["by_model"]["qwen3b"]["answered"]
        if g < q:
            L += [f"**Gemini answered {g} of the {q} questions so far** (its free daily limit ran out); the paired difference "
                  "below uses only the questions both models answered.", ""]
        for label, key in rows:
            L.append(f"| {label} | " + " | ".join(
                f"{pct(qa['by_model'][m][key]['accuracy'])}{ci(qa['by_model'][m][key]['ci95'])}, n = {qa['by_model'][m][key]['scored']}"
                for m in ("gemini", "qwen3b")) + " |")
        for label, key in (("\"Not in the text\" when the photo does not say it (recall)", "not_in_text_recall"),
                           ("\"Not in the text\" although the value was in the text (false)", "false_not_in_text"),
                           ("Answers with a number that is not in the text", "numbers_not_in_text")):
            L.append(f"| {label} | " + " | ".join(
                f"{pct(qa['by_model'][m][key]['rate'])}, {qa['by_model'][m][key]['yes']}/{qa['by_model'][m][key]['of']}"
                for m in ("gemini", "qwen3b")) + " |")
        for label, key in (("First sentence, p50 / p90", "first_sentence_s"), ("Whole answer, p50 / p90", "total_s")):
            L.append(f"| {label} | " + " | ".join(
                f"{sec((qa['by_model'][m][key] or {}).get('p50'))} / {sec((qa['by_model'][m][key] or {}).get('p90'))}"
                for m in ("gemini", "qwen3b")) + " |")
        L.append("| Service errors (after 3 retries) | " + " | ".join(str(qa["by_model"][m]["service_errors"]) for m in ("gemini", "qwen3b")) + " |")
        p = qa["paired"]
        if p["n"]:
            L += ["", f"**Paired difference** on the {p['n']} questions both models answered: Gemini − Qwen = "
                  f"{p['gemini_minus_qwen'] * 100:+.1f} points{ci(p['ci95']).replace(' %', ' pt')}. Both right {p['both_right']}, "
                  f"only Gemini {p['only_gemini']}, only Qwen {p['only_qwen']}, both wrong {p['both_wrong']}."]
        L += ["", "Per question (correct / scored):", "", "| Question | Gemini | Qwen |", "|---|---|---|"]
        keys = sorted(set(qa["by_model"]["gemini"]["by_question"]) | set(qa["by_model"]["qwen3b"]["by_question"]))
        for k in keys:
            cells = []
            for m in ("gemini", "qwen3b"):
                v = qa["by_model"][m]["by_question"].get(k)
                cells.append(f"{v[0]}/{v[1]}" if v else "–")
            L.append(f"| {k} | " + " | ".join(cells) + " |")
        j = qa.get("judge")
        if j:
            L += ["", "**Free-text answers** (uses, warnings, storage, how to use, ...), a random blind sample judged by hand "
                  f"({j['judge']}):", "", "| | correct | partial | wrong | unsupported | correct rate |", "|---|---|---|---|---|---|"]
            for m in ("gemini", "qwen3b"):
                d = j[m]
                L.append(f"| {NAMES[m]} (n = {d['n']}) | {d['correct']} | {d['partial']} | {d['wrong']} | {d['unsupported']} | "
                         f"{pct(d['correct_rate'])}{ci(d['correct_ci95'])} |")

    # ---------------------------------------------------------------- expiry
    if exp:
        s = exp["summary"]
        L += ["", "## 3. Expiry dates", "",
              f"{s['cases']} label texts written with the date formats seen on the real packs (`NOV.26`, `DEC.2026`, `12/2026`, "
              f"`12.2026`, `12-2026`, `10/26`, `APR. 2027`, `JUL 28`, ...) and food wordings (`Best before 14/10/2026`, "
              f"`Use by: 02.12.2026`); {s['expired_cases']} of them expired on the evaluation date, including dates one day "
              "and one month either side of it. Question: \"Has it expired?\"", "",
              "| Who decides | Verdict correct | Wrong verdicts | \"Valid until\" date stated wrongly |", "|---|---|---|---|",
              f"| The app's code alone (`expiry_dates`) | {s['code']['correct']}/{s['code']['scored']} | {', '.join(s['code']['wrong']) or '–'} | – |"]
        for cond, label in (("app", "The app (code verdict given to the model)"), ("llm_only", "Model alone, no date checks (ablation)")):
            for m in ("gemini", "qwen3b"):
                d = s[f"{cond}_{m}"]
                L.append(f"| {label}, {NAMES[m]} | {d['correct']}/{d['scored']} | {', '.join(d['wrong']) or '–'} | "
                         f"{len(d['date_wrong'])} of {d['date_stated']}{(' (' + ', '.join(d['date_wrong']) + ')') if d['date_wrong'] else ''} |")
        L += ["", f"Relative wordings (\"best before 6 months from manufacture\", {s['relative_cases']} cases, reported apart): "
              f"the code finds no date in {s['code_relative']['correct']}/{s['code_relative']['scored']}; the app says so or works it out "
              f"correctly with Gemini in {s['app_gemini_relative']['correct']}/{s['app_gemini_relative']['scored']} and with Qwen in "
              f"{s['app_qwen3b_relative']['correct']}/{s['app_qwen3b_relative']['scored']}."]

    # ---------------------------------------------------------------- web
    if web:
        L += ["", "## 4. Web lookup safety", "",
              f"{len(web['lookups'])} questions the label could not answer, looked up with {web['model']} after consent: "
              f"{web['answered']} answered, {web['labelled']} start with \"According to the web\", "
              f"{web['health_with_reminder']} of {web['health']} health answers end with the pharmacist reminder. "
              f"{web['item_only_blocked']} of {web['item_only_questions']} wordings of expiry, batch, manufacturing date and price "
              "questions are never offered a lookup" + (f" (not blocked: {', '.join(web['item_only_not_blocked'])})" if web["item_only_not_blocked"] else "") + "."]
        review = res("web_review.json")
        if review:
            counts = {}
            for it in review["items"]:
                counts[it["verdict"]] = counts.get(it["verdict"], 0) + 1
            names = {"correct": "correct", "wrong_item": "about a different company or product, stated as fact",
                     "unsupported": "a claim nothing supports", "no_results": "search found nothing"}
            L += ["", "Content of the answers, read by hand (`eval/results/web_review.json`): "
                  + ", ".join(f"{v} {names.get(k, k)}" for k, v in counts.items()) + ". " + review["note"]
                  + " The labelling worked, but the model did not follow the rule \"if the results don't answer the question, say "
                  "so\": it reported facts about other companies as if they were about the item.", "",
                  "| Question | Verdict | Why |", "|---|---|---|"]
            L += [f"| {it['question']} | {names.get(it['verdict'], it['verdict'])} | {it['why']} |" for it in review["items"]]

    # ---------------------------------------------------------------- speed
    if lat:
        o, mch = lat["ops"], lat["machine"]
        L += ["", "## 5. Speed", "",
              f"The real server on {mch['cpu']} ({mch['memory_gb']} GB), {mch['platform']}, Python {mch['python']}, over localhost, "
              f"{lat['runs']} timed runs per operation after one warm-up. Voice: {lat['health'].get('tts_engine')}. Network time "
              "to a phone and the browser's own work (camera, JPEG, speech recognition, starting the audio) are not included.", "",
              "| Operation | p50 | p90 | p95 | mean |", "|---|---|---|---|---|"]
        names = {"live_label": "Live frame round trip, a label (960 px)", "live_spread": "Live frame round trip, a two-page spread",
                 "live_book": "Live frame in book mode (page-turn watch)", "capture": "Capture, a label (1920 px)",
                 "capture_spread": "Capture, a two-page spread (book path)", "ocr_only": "Apple Vision alone (in process)",
                 "preprocess": "Image fixes alone (corrected versions, in process)", "tts": "Voice for one sentence (/api/tts)",
                 "book_page_qwen3b": "Book page with Qwen paragraphs", "book_page_gemini": "Book page with Gemini paragraphs",
                 "ask_first_qwen3b": "Question → first sentence, Qwen", "ask_total_qwen3b": "Question → whole answer, Qwen",
                 "first_word_qwen3b": "Question → first sentence's audio, Qwen", "ask_first_gemini": "Question → first sentence, Gemini",
                 "ask_total_gemini": "Question → whole answer, Gemini", "first_word_gemini": "Question → first sentence's audio, Gemini"}
        for k, label in names.items():
            d = o.get(k)
            if d:
                L.append(f"| {label} | {sec(d['p50'])} | {sec(d['p90'])} | {sec(d['p95'])} | {sec(d['mean'])} |")
        if o.get("first_word_gemini"):
            L += ["", "Gemini's times depend on the load of Google's free tier, not on this Mac: the Gemini runs were made "
                  "while it was often answering HTTP 503 \"model is currently experiencing high demand\", and a reply then "
                  "either came back in about 2 s or stalled for up to two minutes. They are reported as measured."]

    # ---------------------------------------------------------------- book
    if book:
        L += ["", "## 6. Book mode on real books", ""]
        p = book.get("pages")
        if p:
            L += [f"{p['photos']} photos of real book pages ({p['spreads']} two-page spreads), read with book mode's path "
                  "(flatten, spine split, deskew, dewarp, page numbers and running title apart, XY-cut order), then grouped "
                  "into paragraphs by Qwen 3B as book mode does.", "",
                  f"- Printed page numbers right: {p['page_numbers']['yes']}/{p['page_numbers']['of']} "
                  f"(spreads {p['page_numbers_spreads']['yes']}/{p['page_numbers_spreads']['of']})."
                  + (f" The spine was found, and the spread split into its two pages, on {p['spreads_split_in_two']['yes']} of "
                     f"{p['spreads_split_in_two']['of']} spreads; a spread read as one wide page has its printed page numbers "
                     "inside the body text, so none is announced." if p.get("spreads_split_in_two") else ""),
                  (f"- Running title found: {p['running_title']['yes']}/{p['running_title']['of']} pages that have one."
                   if p["running_title"]["of"] else "- No page in the set has a running title."),
                  (f"- The model grouped the paragraphs on {p['arranged_by_model']['yes']} of {p['arranged_by_model']['of']} pages; "
                   "on the others Qwen 3B did not answer within the app's 12-second limit, so the page was read in layout order, "
                   "as book mode does." if p.get("arranged_by_model") and p["arranged_by_model"]["yes"] < p["arranged_by_model"]["of"] else ""),
                  f"- Reading starts at the first body line: layout {p['order_layout']['starts_at_first_line']['yes']}/"
                  f"{p['order_layout']['starts_at_first_line']['of']}, with the model's paragraphs "
                  f"{p['order_arranged_qwen3b']['starts_at_first_line']['yes']}/{p['order_arranged_qwen3b']['starts_at_first_line']['of']}.",
                  f"- Key lines in the right order (pairs): layout {pct(p['order_layout']['rate'])}, with the model's paragraphs "
                  f"{pct(p['order_arranged_qwen3b']['rate'])}."]
        v = book.get("video")
        if v:
            L += [f"- Page-turn video: {v['seconds']} s, {v['turns']} turns, fed at {v['fps_fed']} frames a second: {v['pages_read']} "
                  f"pages read for {v['pages_expected']} shown ({v['missed']} missed, {v['extra']} extra), {v['moved_events']} "
                  "\"moved\" events (the same page shifted, which does not restart reading)."]
            rv = res("book_video_review.json")
            if rv:
                L.append(f"- Checked by eye (`eval/results/book_video_review.json`): {rv['summary']}")

    # ---------------------------------------------------------------- users
    if users:
        L += ["", "## 7. User study", "", f"{len(users)} people ({', '.join(sorted({r['vision'] for r in users}))}), protocol in "
              "`markdown/user_study.md`.", "", "| Statement | Mean (1–5) |", "|---|---|"]
        for k, label in (("q_useful", "Useful"), ("q_easy", "Easy to get the item into view"), ("q_answers", "Answers correct"),
                         ("q_speed", "Fast enough"), ("q_voice", "Voice clear"), ("q_overall", "Overall (the user rating)")):
            vals = [float(r[k]) for r in users if r[k]]
            L.append(f"| {label} | {statistics.mean(vals):.2f} (n = {len(vals)}) |" if vals else f"| {label} | – |")
        for k, label in (("t2_success", "expired and batch"), ("t3_success", "food ingredients"), ("t4_success", "book page turn"),
                         ("t5_success", "not on the label, web lookup")):
            L.append(f"\n- Task \"{label}\": {sum(r[k] == '1' for r in users)}/{len(users)} succeeded.")
        times = [float(r["t1_seconds"]) for r in users if r["t1_seconds"]]
